    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username dan Password tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        //untuk admin
        AdminController ac = new AdminController();
        if (ac.cekLogin(username, password)) {
            JOptionPane.showMessageDialog(this, "Login Berhasil sebagai Member");
            new AdminDashboard(ac.adminLogin).setVisible(true);
            this.dispose();
            return;
        }

        //untuk member
        MemberController mc = new MemberController();
        if (mc.cekLogin(username, password)) {
            JOptionPane.showMessageDialog(this, "Login Berhasil sebagai Member");
            new MemberDashboard(mc.memberLogin).setVisible(true);
            this.dispose();
            return;
        }
        
        JOptionPane.showMessageDialog(this, "Username atau password salah",
            "Login Gagal", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_btnLoginActionPerformed

