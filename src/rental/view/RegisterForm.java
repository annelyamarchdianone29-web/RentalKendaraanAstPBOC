    private void btnSignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignUpActionPerformed
        // TODO add your handling code here:
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();
        String konfirmasi = new String(txtKonfirmasi.getPassword()).trim();
        String nama = txtNama.getText().trim();
        String noHp = txtHp.getText().trim();

        //validasi
        if (username.isEmpty() || password.isEmpty() || konfirmasi.isEmpty()
                || nama.isEmpty() || noHp.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua data wajib diisi!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!password.equals(konfirmasi)) {
            JOptionPane.showMessageDialog(this, "Password dan konfirmasi tidak sama!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!noHp.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "No HP harus berupa angka!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        MemberController mc = new MemberController();

        if (mc.cekUsername(username)) {
            JOptionPane.showMessageDialog(this, "Username sudah dipakai, pilih yang lain");
            return;
        }

        // Simpan
        Member m = new Member();
        m.setUsername(username);
        m.setPassword(password);
        m.setNama(nama);
        m.setNoHp(noHp);

        if (mc.daftar(m)) {
            JOptionPane.showMessageDialog(this, "Pendaftaran berhasil, silakan login");
            new LoginForm().setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Pendaftaran gagal");
        }
    }//GEN-LAST:event_btnSignUpActionPerformed

