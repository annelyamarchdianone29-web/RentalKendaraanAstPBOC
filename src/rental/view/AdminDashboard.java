    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        double harga = validasiForm();
        if (harga < 0) {
            return;
        }

        String kode = txtKode.getText().trim();
        if (kc.cekKode(kode)) {
            JOptionPane.showMessageDialog(this, "Kode kendaraan sudah dipakai!");
            return;
        }

        Kendaraan k = new Kendaraan();
        k.setKodeKendaraan(kode);
        k.setMerk(txtMerk.getText().trim());
        k.setJenis(cmbJenis.getSelectedItem().toString());
        k.setHargaPerHari(harga);
        k.setStatus(cmbStatus.getSelectedIndex());   // 0 = Ready, 1 = Disewa

        if (kc.tambah(k)) {
            JOptionPane.showMessageDialog(this, "Kendaraan berhasil ditambahkan");
            kosongkanForm();
            loadKendaraan();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (lblId.getText().equals("-")) {
            JOptionPane.showMessageDialog(this, "Pilih kendaraan di tabel dulu!");
            return;
        }
        double harga = validasiForm();
        if (harga < 0) {
            return;
        }

        int id = Integer.parseInt(lblId.getText());
        String kode = txtKode.getText().trim();

        if (kc.cekKodeEdit(kode, id)) {
            JOptionPane.showMessageDialog(this, "Kode kendaraan sudah dipakai kendaraan lain!");
            return;
        }

        Kendaraan k = new Kendaraan();
        k.setId(id);
        k.setKodeKendaraan(kode);
        k.setMerk(txtMerk.getText().trim());
        k.setJenis(cmbJenis.getSelectedItem().toString());
        k.setHargaPerHari(harga);
        k.setStatus(cmbStatus.getSelectedIndex());

        if (kc.ubah(k)) {
            JOptionPane.showMessageDialog(this, "Data berhasil diubah");
            kosongkanForm();
            loadKendaraan();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal mengubah data");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed
