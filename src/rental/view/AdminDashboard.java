    private void kosongkanForm() {
        lblId.setText("-");
        txtMerk.setText("");
        txtHarga.setText("");
        cmbJenis.setSelectedIndex(0);
        cmbStatus.setSelectedIndex(0);
        tblKendaraan.clearSelection();
        isiKodeOtomatis();
    }

    private void isiKodeOtomatis() {
        txtKode.setText(kc.buatKode(cmbJenis.getSelectedItem().toString()));
    }

    private double validasiForm() {
        if (txtKode.getText().trim().isEmpty() || txtMerk.getText().trim().isEmpty()
                || txtHarga.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua data wajib diisi!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return -1;
        }
        try {
            double harga = Double.parseDouble(txtHarga.getText().trim());
            if (harga <= 0) {
                JOptionPane.showMessageDialog(this, "Harga harus lebih dari 0!");
                return -1;
            }
            return harga;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga harus berupa angka!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return -1;
        }
    }

