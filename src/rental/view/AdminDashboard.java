    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (lblId.getText().equals("-")) {
            JOptionPane.showMessageDialog(this, "Pilih kendaraan di tabel dulu!");
            return;
        }
        int id = Integer.parseInt(lblId.getText());

        if (kc.sedangDisewa(id)) {
            JOptionPane.showMessageDialog(this, "Kendaraan sedang disewa, tidak bisa dinonaktifkan!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int ok = JOptionPane.showConfirmDialog(this,
                "Nonaktifkan kendaraan " + txtKode.getText() + "?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (ok != JOptionPane.YES_OPTION) {
            return;
        }

        if (kc.nonaktifkan(id)) {
            JOptionPane.showMessageDialog(this, "Kendaraan dinonaktifkan");
            kosongkanForm();
            loadKendaraan();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menonaktifkan");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

